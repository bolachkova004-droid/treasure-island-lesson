/* к утренним сценам — пословица дня */
const SAYINGS = { 1:'Не зная броду, не суйся в воду.', 2:'Утро вечера мудренее.', 3:'Что посеешь, то и пожнёшь.', 4:'Правда в огне не горит и в воде не тонет.', 5:'Куда иголка, туда и нитка.' };
function loreHook(id, sc){
  if(!st.lore) st.lore = [];
  if(id === 'morning' && SAYINGS[st.day]) sc.text.unshift(`<p class="saying">${SAYINGS[st.day]}</p>`);
  const k = LORE_AT[id]; if(!k || st.lore.includes(k)) return;
  st.lore.push(k); const L = LORE[k];
  sc.text.push(`<div class="lore"><span class="lore-k">Поверье · ${L.t}</span>${L.x}</div>`);
  setTimeout(() => { toast('Поверье записано в тетрадь'); sfx('lore'); }, 400);
}
