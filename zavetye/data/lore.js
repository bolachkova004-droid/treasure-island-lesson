function loreHook(id, sc){
  if(!st.lore) st.lore = [];
  const k = LORE_AT[id]; if(!k || st.lore.includes(k)) return;
  st.lore.push(k); const L = LORE[k];
  sc.text.push(`<div class="lore"><span class="lore-k">${LORE_BY[L.by]} · ${L.t}</span>${L.x}</div>`);
  setTimeout(() => { toast('В тетрадь: поверье «' + L.t + '»'); sfx('lore'); }, 400);
}

