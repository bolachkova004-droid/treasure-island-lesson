function morningScene(){
  const d = st.day, T = [];
  const wd = dayName(d);
  const lead = {
    2:'Четверг. За ночь кто-то вымел сени и поставил веник в угол, вверх прутьями.',
    3:'Пятница. С Нижней улицы доносится стук: Гриша прибивает к чемодану новый ремень.',
    4:'Суббота. В шесть сорок Анна просыпается сама, будто её толкнули. Где-то за полем гудит мотор автобуса. Гул приближается, стоит на месте ровно столько, сколько стоят на остановке, и уходит. По субботам здесь никаких автобусов нет.',
  }[d] || (wd + '. Ещё один день в Заветье.');
  T.push(lead);
  if(F('greeted')) T.push('Ночью кто-то подкладывал дрова. В доме тепло, как бывает у хороших хозяев для хороших гостей.');
  else T.push('Ночью в углу, где стоит прялка, до рассвета что-то шуршало.');
  if(F('silentEntry') && F('hasNotebook') && !has('c_forged') && !st.outcome){
    T.push('Тетрадь Гриши лежит не там, где Анна её оставила. Из неё торчит листок, которого вчера не было.');
    T.push(gain('c_forged', true));
    T.push('Из угла, где стоит прялка, доносится сухой смешок. Будто кто-то очень доволен своей работой.');
  }
  if(F('grunyaNoticed') && !F('basket')){
    setF('basket');
    T.push('На крыльце стоит корзинка: пироги и записка от Груни печатными буквами. «ЕШЬ». Больше ничего.');
  }
  return { art:'house', place:'Дом Аглаи · ' + wd.toLowerCase(), title:'Утро', text:T, choices:[ back() ] };
}
