/* давление в разговоре: настойчивые вопросы закрывают собеседника до конца дня */
function press(who, n = 1){ const P = st.press; if(P.day !== st.day){ for(const k in P) delete P[k]; P.day = st.day; } P[who] = (P[who] || 0) + n; }
const pressed = (who, lim) => st.press && st.press.day === st.day && (st.press[who] || 0) >= lim;


